// Build step: one source for each piece of logic, copied to where it runs.
//   npm run build
//  1. officescripts/GenerateGatePassQR.ts  <- qr/office-main.ts + qr/qr-core.ts
//  2. qr/qr-core.js                        <- qr/qr-core.ts (for the prototype and tests)
//  3. config/settings.json, config/reason-codes.json <- rules/rules.js
//  4. sharepoint/list-schema.json, docs/02-data-model.md <- tools/schema-src.js
//  5. prototype/index.html                 <- prototype/src (UI reference; admin set-up code disabled)
const fs = require('fs');
const path = require('path');
const ts = require('typescript');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, s) => { fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true }); fs.writeFileSync(path.join(root, p), s); console.log('wrote', p, s.length, 'bytes'); };

const core = read('qr/qr-core.ts');
const officeHeader = `// GenerateGatePassQR — Office Script for GrantedPA
// GENERATED by tools/build.js from qr/office-main.ts + qr/qr-core.ts. Edit those, then rebuild.
//
// Install: Excel for the web > Automate > New script > paste this file > Save as "GenerateGatePassQR".
// Call it from Power Automate with Excel Online (Business) > "Run script" against QR-Runner.xlsx.
// Input:  passCode (text, e.g. DDC2-7KQX9M)
// Output: { passCode, svg, pngBase64, version, modules }

`;
write('officescripts/GenerateGatePassQR.ts', officeHeader + read('qr/office-main.ts') + '\n' + core);
// The one script the flows call: rules, QR and admin-code check together (see officescripts/engine/).
const engineHeader = `// GrantedEngine — Office Script for GrantedPA
// GENERATED by tools/build.js from officescripts/engine/*.ts, qr/qr-core.ts and officescripts/CheckAdminCode.ts.
// Edit those, then rebuild. setup/Setup-GrantedPA.ps1 uploads it (as GrantedEngine.osts) to the QRRunner library;
// the flows run it with Excel Online (Business) → Run script from SharePoint library, against QR-Runner.xlsx.

`;
const adminCheck = read('officescripts/CheckAdminCode.ts').replace('function main(workbook: ExcelScript.Workbook, code: string, stored: string): boolean {', 'function checkAdminCodeMain(workbook: ExcelScript.Workbook, code: string, stored: string): boolean {');
if (!adminCheck.includes('function checkAdminCodeMain(')) throw new Error('CheckAdminCode.ts main() signature changed');
const engine = engineHeader + read('officescripts/engine/engine-main.ts') + '\n' + read('officescripts/engine/engine-core.ts') + '\n' + core.replace(/^[\s\S]*?(?=interface QrMatrix)/, '') + '\n' + adminCheck;
write('officescripts/GrantedEngine.ts', engine);
// .osts is the file Excel saves an Office Script as: JSON holding the source and its parameter schema.
const osts = {
  version: '0.3.0',
  body: engine,
  description: 'Granted rules, gate-pass QR codes and admin set-up code check. Called by the Granted flows.',
  noCodeMetadata: '',
  parameterInfo: JSON.stringify({
    version: 1,
    originalParameterOrder: [{ name: 'op', index: 0 }, { name: 'input', index: 1 }],
    parameterSchema: { type: 'object', required: ['op', 'input'], properties: { op: { type: 'string' }, input: { type: 'string' } } },
    returnSchema: { type: 'object', properties: { result: { type: 'string' } } },
    signature: { comment: '', parameters: [{ name: 'workbook', comment: '' }, { name: 'op', comment: '' }, { name: 'input', comment: '' }] },
  }),
  apiInfo: JSON.stringify({ variant: 'synchronous', variantVersion: 2 }),
};
write('officescripts/GrantedEngine.osts', JSON.stringify(osts));

const js = ts.transpileModule(core, { compilerOptions: { target: ts.ScriptTarget.ES2017, removeComments: false } }).outputText;
write('qr/qr-core.js', '// GENERATED from qr/qr-core.ts by tools/build.js\n' + js);

const R = require(path.join(root, 'rules/rules.js'));
write('config/settings.json', JSON.stringify(R.DEFAULT_SETTINGS, null, 2) + '\n');
const reasons = Object.entries(R.REASONS).map(([code, r]) => ({ code, key: r.key, outcome: r.outcome, title: r.title, remedy: r.remedy }));
write('config/reason-codes.json', JSON.stringify(reasons, null, 2) + '\n');
require('./schema-src.js');
require('./gen-docs.js');

// The prototype is a UI reference only. The admin set-up code is never in this repository,
// so the build always leaves admin set-up disabled.
const dataUri = (p) => 'data:image/png;base64,' + fs.readFileSync(path.join(root, p)).toString('base64');
let html = read('prototype/src/granted.html');
html = html.replace('/*@@RULES@@*/', () => read('rules/rules.js'))
  .replace('/*@@ACCOUNTS@@*/', () => read('rules/accounts.js'))
  .replace('/*@@QR@@*/', () => js)
  .replace('/*@@DATA@@*/', () => read('prototype/src/granted-data.js'))
  .split('@@LOGO_WHITE@@').join(dataUri('assets/brand/logo-white-400.png'))
  .split('@@LOGO_BLUE@@').join(dataUri('assets/brand/logo-blue-400.png'))
  .split('@@ADMIN_CODE_HASH@@').join('');
write('prototype/index.html', html);
